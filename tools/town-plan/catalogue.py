#!/usr/bin/env python3
"""Build the owner-review catalogue from this checkout's game data.

Run from anywhere: python3 tools/town-plan/catalogue.py
The classification documents the v7 capability utility producer; it is not a
runtime reduction table. Black Market rows are allocation candidates, not a
promise that store_create_random/black_market_ok will accept a particular item.
"""
from pathlib import Path
from collections import defaultdict
import json

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / 'angband/lib/gamedata'
OUT = ROOT / 'docs/town-item-catalogue.html'


def clean(name):
    return name.removeprefix('& ').replace('~', '').replace('|', '').strip()


def records(path):
    result = []
    for line_no, line in enumerate(path.read_text().splitlines(), 1):
        if line.startswith('name:'):
            result.append({'name': clean(line[5:]), 'line': line_no, 'fields': defaultdict(list)})
        elif result and ':' in line and not line.startswith('#'):
            key, val = line.split(':', 1)
            result[-1]['fields'][key].append(val)
    return result


objects = records(DATA / 'object.txt')
by_key = {}
for obj in objects:
    obj['type'] = obj['fields']['type'][0]
    by_key[(obj['type'], obj['name'].lower())] = obj

# Books are generated by the class parser, rather than object.txt.
books = {}
for n, line in enumerate((DATA / 'class.txt').read_text().splitlines(), 1):
    if line.startswith('book:'):
        _, typ, location, name, *_ = line.split(':')
        key = (typ, name.lower())
        if key not in books or location == 'town':
            books[key] = {'name': name, 'type': typ, 'line': n, 'location': location,
                          'fields': defaultdict(list), 'source': 'class.txt'}
by_key.update(books)

shops = {'STORE_GENERAL': 'General Store', 'STORE_ARMOR': 'Armoury',
         'STORE_WEAPON': 'Weaponsmith', 'STORE_BOOK': 'Bookseller',
         'STORE_ALCHEMY': 'Alchemist', 'STORE_MAGIC': 'Magic Shop'}
offers = defaultdict(list)
shop = None
explicit = 0
for line in (DATA / 'store.txt').read_text().splitlines():
    if line.startswith('store:'):
        shop = line.split(':')[1]
    elif shop in shops and line.startswith(('normal:', 'always:')):
        mode, typ, *name = line.split(':')
        typ = typ.replace('armour', 'armor')
        if not name:
            keys = [k for k, b in books.items() if k[0] == typ and b['location'] == 'town']
        else:
            needle = clean(name[0]).lower()
            keys = [(typ, needle)] if (typ, needle) in by_key else [k for k in by_key if k[0] == typ and needle in k[1]]
            if len(keys) != 1:
                raise ValueError((line, keys))
        for key in keys:
            offers[key].append(f'{shops[shop]} ({mode})')
            explicit += 1

# Include kinds the Black Market can draw from the normal allocation table.
# Its price, quality, duplicate-stock and curse filters run on generated items.
for key, obj in by_key.items():
    alloc = obj['fields']['alloc']
    if obj['type'] not in ('chest', 'gold', 'none') and any(int(a.split(':')[0]) > 0 for a in alloc):
        offers[key].append('Black Market (allocation candidate)')
# Dungeon books are allocated by class data; show them without claiming stock.
for key, book in books.items():
    offers[key].append('Black Market (book allocation candidate)')

food = {'Apple', 'Ration of Food', 'Slime Mold', 'Draught of the Ents',
        'Pint of Fine Wine', 'Sip of Miruvor', 'Piece of Elvish Waybread',
        'Honey-cake', 'Slice of Meat', 'Handful of Dried Fruits'}
gear = {'sword', 'polearm', 'hafted', 'bow', 'boots', 'gloves', 'helm', 'crown',
        'shield', 'cloak', 'soft armor', 'hard armor', 'dragon armor', 'ring', 'amulet'}


def role(obj):
    typ, name = obj['type'], obj['name']
    effects = obj['fields']['effect']
    if typ in gear:
        return 'Power', 'positive equipped borg_power gain', 'Equipment try-on; the supply model never borrows consumable inventory-power bonuses.'
    if typ == 'light':
        return 'Light', 'remaining fuel turns / copy', 'Current worn fuel and compatible spares share endurance coverage; permanent light suppresses fuel demand.'
    if typ == 'flask':
        return 'Ranged damage + fuel', 'throw damage; 7500 lantern-fuel turns', 'Attack supply competes with arrows and devices. Fuel applies only with a lantern; oil is not another light source.'
    if typ in ('shot', 'arrow', 'bolt'):
        return 'Ranged damage', 'average damage × matching launcher multiplier', 'Zero without a matching launcher; carried pack and quiver stock share diminishing coverage.'
    if typ == 'digger':
        return 'Digging', 'digging tool availability', 'Shared with Stone to Mud; retaining a tool and buying one use the same supply facts.'
    if typ.endswith('book'):
        return 'Spell access', 'one usable class book', 'Only the player class and books with level/mana-eligible spells count. Owning it closes the same access requirement; duplicates do not unlock more spells.'
    mapping = {'HEAL_HP':'Healing', 'CURE':'Condition cures', 'TIMED_DEC':'Condition cures',
               'NOURISH':'Food', 'RECALL':'Recall', 'TELEPORT':'Escape', 'TELEPORT_LEVEL':'Level escape',
               'TELEPORT_TO':'Teleport Other', 'RESTORE_MANA':'Mana', 'RESTORE_EXP':'Restore experience',
               'GAIN_EXP':'Experience', 'RESTORE_STAT':'Restore stats', 'GAIN_STAT':'Stat growth',
               'REMOVE_CURSE':'Remove Curse', 'ENCHANT':'Enchantment', 'RECHARGE':'Recharging',
               'MAP_AREA':'Mapping', 'LIGHT_AREA':'Illumination', 'LIGHT_LEVEL':'Mapping',
               'IDENTIFY':'Rune identification', 'GLYPH':'Glyph', 'BANISH':'Banishment',
               'MASS_BANISH':'Banishment', 'DESTRUCTION':'Destruction', 'EARTHQUAKE':'Destruction',
               'BRAND_WEAPON':'Enchantment', 'BRAND_AMMO':'Enchantment', 'BRAND_BOLTS':'Enchantment'}
    roles = set()
    harmful_food = any(e.startswith(('TIMED_INC:CONFUSED', 'TIMED_INC:POISONED', 'TIMED_INC_NO_RES:PARALYZED')) for e in effects)
    for effect in effects:
        parts = effect.split(':'); head = parts[0]; sub = parts[1] if len(parts) > 1 else ''
        if head == 'NOURISH' and (harmful_food or sub in ('DEC_BY', 'SET_TO')):
            continue
        if head in ('TIMED_INC','TIMED_INC_NO_RES','TIMED_SET'):
            if sub in ('FAST','SPRINT'): roles.add('Speed')
            elif sub.startswith('OPP_'): roles.add('Temporary resistance')
            elif sub in ('BOLD','HERO','SHERO','BLESSED','SHIELD','STONESKIN','PROTEVIL','INVULN') or sub.startswith('ATT_'): roles.add('Combat buff')
            elif sub in ('SINVIS','TELEPATHY'): roles.add('Detection')
        elif sub.startswith('AWAY_'):
            roles.add('Teleport Other')
        elif sub == 'KILL_WALL': roles.add('Digging')
        elif sub in ('MON_HEAL','MON_SPEED','MON_CLONE','MON_POLY'):
            continue
        elif head.startswith('DETECT_') or head.startswith('SENSE_') or head in ('PROBE','READ_MINDS'): roles.add('Detection')
        elif head in ('LINE','BOLT','BOLT_OR_BEAM','BEAM','BALL','BREATH','ARC','SHORT_BEAM','SWARM','STRIKE','STAR','STAR_BALL','SPOT','SPHERE','PROJECT_LOS','PROJECT_LOS_AWARE','BOLT_AWARE','WONDER'): roles.add('Ranged damage')
        elif head in ('BOLT_STATUS','BOLT_STATUS_DAM','TOUCH','TOUCH_AWARE','MON_TIMED_INC'): roles.add('Combat control')
        elif head in mapping: roles.add(mapping[head])
    if roles:
        return ' + '.join(sorted(roles)), 'native effect amounts; devices use charges/cooldown', 'All mapped effects contribute. Repairs require a relevant deficit; mana requires a caster. Substitutes share coverage. Known carried stock, devices and usable information spells reduce replenishment value.'
    return 'Excluded', 'no positive known-use utility', 'No mapped safe service: harmful/monster-aiding effects, or route-changing/random services outside this supply policy. Unknown first-copy learning remains separate.'


rows = []
for key in sorted(offers):
    obj = by_key[key]
    need, unit, note = role(obj)
    source = obj.get('source', 'object.txt')
    rows.append({'kind': obj['name'], 'type': obj['type'], 'shops': '; '.join(offers[key]),
                 'need': need, 'unit': unit, 'note': note,
                 'source': f'../angband/lib/gamedata/{source}#L{obj["line"]}'})

payload = json.dumps(rows, ensure_ascii=False).replace('<', '\\u003c')
