#!/usr/bin/env python3
"""Build the owner-review catalogue from this checkout's game data.

Run from anywhere: python3 tools/town-plan/catalogue.py
The classification documents the shadow producer at 5203a06; it is not a
runtime reduction table. Black Market rows are allocation candidates, not a
promise that store_create_random/black_market_ok will accept a particular item.
"""
from pathlib import Path
from collections import defaultdict
import json

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / 'angband/lib/gamedata'
OUT = ROOT / 'docs/town-item-catalogue.html'


def clean(name):
    return name.removeprefix('& ').replace('~', '').replace('|', '').strip()


def records(path):
    result = []
    for line_no, line in enumerate(path.read_text().splitlines(), 1):
        if line.startswith('name:'):
            result.append({'name': clean(line[5:]), 'line': line_no, 'fields': defaultdict(list)})
        elif result and ':' in line and not line.startswith('#'):
            key, val = line.split(':', 1)
            result[-1]['fields'][key].append(val)
    return result


objects = records(DATA / 'object.txt')
by_key = {}
for obj in objects:
    obj['type'] = obj['fields']['type'][0]
    by_key[(obj['type'], obj['name'].lower())] = obj

# Books are generated by the class parser, rather than object.txt.
books = {}
for n, line in enumerate((DATA / 'class.txt').read_text().splitlines(), 1):
    if line.startswith('book:'):
        _, typ, location, name, *_ = line.split(':')
        key = (typ, name.lower())
        if key not in books or location == 'town':
            books[key] = {'name': name, 'type': typ, 'line': n, 'location': location,
                          'fields': defaultdict(list), 'source': 'class.txt'}
by_key.update(books)

shops = {'STORE_GENERAL': 'General Store', 'STORE_ARMOR': 'Armoury',
         'STORE_WEAPON': 'Weaponsmith', 'STORE_BOOK': 'Bookseller',
         'STORE_ALCHEMY': 'Alchemist', 'STORE_MAGIC': 'Magic Shop'}
offers = defaultdict(list)
shop = None
explicit = 0
for line in (DATA / 'store.txt').read_text().splitlines():
    if line.startswith('store:'):
        shop = line.split(':')[1]
    elif shop in shops and line.startswith(('normal:', 'always:')):
        mode, typ, *name = line.split(':')
        typ = typ.replace('armour', 'armor')
        if not name:
            keys = [k for k, b in books.items() if k[0] == typ and b['location'] == 'town']
        else:
            needle = clean(name[0]).lower()
            keys = [(typ, needle)] if (typ, needle) in by_key else [k for k in by_key if k[0] == typ and needle in k[1]]
            if len(keys) != 1:
                raise ValueError((line, keys))
        for key in keys:
            offers[key].append(f'{shops[shop]} ({mode})')
            explicit += 1

# Include kinds the Black Market can draw from the normal allocation table.
# Its price, quality, duplicate-stock and curse filters run on generated items.
for key, obj in by_key.items():
    alloc = obj['fields']['alloc']
    if obj['type'] not in ('chest', 'gold', 'none') and any(int(a.split(':')[0]) > 0 for a in alloc):
        offers[key].append('Black Market (allocation candidate)')
# Dungeon books are allocated by class data; show them without claiming stock.
for key, book in books.items():
    offers[key].append('Black Market (book allocation candidate)')

food = {'Apple', 'Ration of Food', 'Slime Mold', 'Draught of the Ents',
        'Pint of Fine Wine', 'Sip of Miruvor', 'Piece of Elvish Waybread',
        'Honey-cake', 'Slice of Meat', 'Handful of Dried Fruits'}
gear = {'sword', 'polearm', 'hafted', 'bow', 'boots', 'gloves', 'helm', 'crown',
        'shield', 'cloak', 'soft armor', 'hard armor', 'dragon armor', 'ring', 'amulet'}


def role(obj):
    typ, name = obj['type'], obj['name']
    effects = obj['fields']['effect']
    harmful = any(e.startswith('CRUNCH') or e.startswith('TIMED_INC:CONFUSED') for e in effects)
    food_ok = not harmful and ((typ == 'food' and name in food) or
                              (typ == 'mushroom' and 'NOURISH:INC_BY' in effects))
    poison_food = typ in ('food', 'mushroom') and not harmful and 'CURE:POISONED' in effects
    if typ == 'light':
        return 'Light', '1 source / copy', 'Target 1, or 2 at descent target ≥ 15. Fuel and radius do not change the unit.'
    if typ == 'scroll' and name in ('Phase Door', 'Word of Recall'):
        return ('Escape', '1 escape / copy', 'Target 1 per five-level trip.') if name == 'Phase Door' else ('Trip', '1 recall / copy', 'Target 2; carried BI_RECALL also includes rods, spells and gear.')
    if food_ok:
        return 'Food', '1 food count / copy', 'Target 10. Also cures poison in urgent pass.' if poison_food else 'Target 10; nutrition is not converted to turns.'
    if poison_food or (typ == 'potion' and name == 'Neutralize Poison'):
        return 'Poison', '1 cure / copy', 'Only valued while poisoned with no alternative cure.'
    if typ == 'potion' and name in ('Cure Light Wounds', 'Cure Serious Wounds', 'Cure Critical Wounds'):
        return 'Healing', '1 wound cure / copy', 'Target 5; all three strengths have equal units.' + (' Also serves urgent Poison; primary value is Healing.' if name == 'Cure Critical Wounds' else '')
    if typ in gear:
        return 'Power', 'Δ borg_power / equipped copy', 'Try-on against current equipment; gap 200000, weight 50. Gain may be zero or negative.'
    note = 'No direct purchase value once known.'
    if typ == 'scroll' and name == 'Remove Hunger':
        note = 'GAP: carried BI_FOOD counts it, but purchase/urgent Food mapping omits it.'
    elif typ in ('wand', 'staff', 'rod'):
        note = 'GAP: no direct device role; carried traits may count capabilities or charges.'
    elif typ.endswith('book'):
        note = 'GAP: no direct spellbook role; class and spell access are not priced.'
    elif typ in ('shot', 'arrow', 'bolt', 'digger'):
        note = 'GAP: no purchase try-on or direct need role.'
    elif typ == 'flask':
        note = 'GAP: fuel is not a light source and has no direct role.'
    elif typ == 'food':
        note = 'Not in the ten-food whitelist, even if the game nourishes the character.'
    elif typ == 'potion' and name in ('Healing', '*Healing*', 'Life'):
        note = 'GAP: not one of the three wound potions mapped to Healing.'
    return 'None', '0 direct need units', note


rows = []
for key in sorted(offers):
    obj = by_key[key]
    need, unit, note = role(obj)
    source = obj.get('source', 'object.txt')
    rows.append({'kind': obj['name'], 'type': obj['type'], 'shops': '; '.join(offers[key]),
                 'need': need, 'unit': unit, 'note': note,
                 'source': f'../angband/lib/gamedata/{source}#L{obj["line"]}'})

payload = json.dumps(rows, ensure_ascii=False).replace('<', '\\u003c')
